#[test]
fn ineligible_voter_rejected() {
    let f = fixture();
    open_window(&f);
    let c = vote_client(&f);

    // no credential at all
    let stranger = Address::generate(&f.env);
    let res = c.try_cast_public(&f.proposal_id, &stranger, &0);
    assert_contract_err(res, Error::NotEligible);

    // credential revoked mid-window
    let identity = IdentityContractClient::new(&f.env, &f.identity);
    identity.revoke(&f.voter2, &b(&f.env, 0xee));
    let res = c.try_cast_public(&f.proposal_id, &f.voter2, &0);
    assert_contract_err(res, Error::NotEligible);
    assert_eq!(identity.get_credential(&f.voter2).unwrap().status, 2u32);
    assert_eq!(STATUS_ACTIVE, 0u32);
}

