/// `try_*` on a non-Result entrypoint returns
/// `Result<Result<T, ConversionError>, Result<soroban_sdk::Error, InvokeError>>`.
/// Contract errors surface as the `Ok(host_error)` arm; decode them back to
/// the crate's `Error` enum via the `TryFrom` impl generated by `contracterror`.
fn assert_contract_err<T>(
    res: Result<Result<T, ConversionError>, Result<soroban_sdk::Error, InvokeError>>,
    expected: Error,
) {
    match res {
        Err(Ok(host_err)) => assert_eq!(Error::try_from(host_err).ok(), Some(expected)),
        Err(Err(_)) => panic!("expected contract error, got host invoke error"),
        Ok(_) => panic!("expected contract error {expected:?}, got success"),
    }
}

const HOUR: u64 = 3_600;
const T0: u64 = 1_000_000;

fn b(env: &Env, v: u8) -> BytesN<32> {
    BytesN::from_array(env, &[v; 32])
}

struct Fixture {
    env: Env,
    admin: Address,
    voter1: Address,
    voter2: Address,
    identity: Address,
    proposal: Address,
    vote: Address,
    proposal_id: u64,
}

/// Registers identity + proposal + vote contracts wired together, issues two
/// eligible credentials, creates one proposal windowed [T0+2h, T0+10h].
fn fixture() -> Fixture {
    let env = Env::default();
    env.mock_all_auths();
    env.ledger().set_timestamp(T0);

    let admin = Address::generate(&env);
    let proposer = Address::generate(&env);
    let voter1 = Address::generate(&env);
    let voter2 = Address::generate(&env);

    let identity_id = env.register(IdentityContract, (admin.clone(),));
    let identity = IdentityContractClient::new(&env, &identity_id);
    identity.issue(&voter1, &b(&env, 0x01), &symbol_short!("citizen"));
    identity.issue(&voter2, &b(&env, 0x02), &symbol_short!("citizen"));

    let proposal_id_addr = env.register(ProposalContract, (admin.clone(),));
    let proposal = ProposalContractClient::new(&env, &proposal_id_addr);
    let proposal_id = proposal.create(
        &proposer,
        &b(&env, 0x11),
        &b(&env, 0x12),
        &b(&env, 0x13),
        &String::from_str(
            &env,
            "bafybeigdyrzt5sfp7udm7hu76uh7y26nf3efuylqabf3oclgtqy55fbzdi",
        ),
        &b(&env, 0x14),
        &(T0 + 2 * HOUR),
        &(T0 + 10 * HOUR),
    );

    let vote_id = env.register(
        Contract,
        (admin.clone(), identity_id.clone(), proposal_id_addr.clone()),
    );

    Fixture {
        env,
        admin,
        voter1,
        voter2,
        identity: identity_id,
        proposal: proposal_id_addr,
        vote: vote_id,
        proposal_id,
    }
}

fn vote_client(f: &Fixture) -> ContractClient<'_> {
    ContractClient::new(&f.env, &f.vote)
}

fn open_window(f: &Fixture) {
    f.env.ledger().set_timestamp(T0 + 3 * HOUR);
}

#[test]
fn public_vote_tallies_once_per_voter() {
    let f = fixture();
    open_window(&f);
    let c = vote_client(&f);

    let t = c.cast_public(&f.proposal_id, &f.voter1, &0);
    assert_eq!(t.total, 1);
    assert_eq!(t.public_votes, 1);
    assert_eq!(t.commitment_votes, 0);
    assert_eq!(t.verification_mode, Symbol::new(&f.env, "public_v1"));
    assert_eq!(t.counts.get(0).unwrap(), 1);

    let t = c.cast_public(&f.proposal_id, &f.voter2, &1);
    assert_eq!(t.total, 2);
    assert_eq!(t.counts.get(0).unwrap(), 1);
    assert_eq!(t.counts.get(1).unwrap(), 1);

    assert!(c.has_voted_public(&f.proposal_id, &f.voter1));
    assert!(!c.has_voted_public(&f.proposal_id, &f.admin));

    // stored tally readable
    let stored = c.get_tally(&f.proposal_id).unwrap();
    assert_eq!(stored.total, 2);
    assert_eq!(stored.verification_mode, Symbol::new(&f.env, "public_v1"));
}

#[test]
fn double_public_vote_rejected() {
    let f = fixture();
    open_window(&f);
    let c = vote_client(&f);
    c.cast_public(&f.proposal_id, &f.voter1, &0);
    let res = c.try_cast_public(&f.proposal_id, &f.voter1, &2);
    assert_contract_err(res, Error::AlreadyVoted);
}

