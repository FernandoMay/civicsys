#[test]
fn commitment_ballot_counts_with_honest_mode() {
    let f = fixture();
    open_window(&f);
    let c = vote_client(&f);
    c.set_membership_root(&f.proposal_id, &b(&f.env, 0x77));

    let t = c.cast_commitment(
        &f.proposal_id,
        &1,
        &b(&f.env, 0xa1),
        &b(&f.env, 0xc1),
        &b(&f.env, 0x77),
        &b(&f.env, 0xd1),
    );
    assert_eq!(t.total, 1);
    assert_eq!(t.commitment_votes, 1);
    assert_eq!(t.public_votes, 0);
    // honesty: commitment mode is recorded, never zk_*
    assert_eq!(t.verification_mode, Symbol::new(&f.env, "commitment_v1"));
    assert_eq!(t.counts.get(1).unwrap(), 1);
    assert!(c.nullifier_seen(&f.proposal_id, &b(&f.env, 0xa1)));
    assert!(!c.nullifier_seen(&f.proposal_id, &b(&f.env, 0xa2)));
    assert_eq!(c.membership_root(&f.proposal_id), Some(b(&f.env, 0x77)));
}

#[test]
